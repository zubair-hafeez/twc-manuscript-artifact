"""Build paper tables from the saved summaries. This does not rerun experiments."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TABLES = ROOT / "manuscript" / "tables"


def read_json(path):
    return json.loads((ROOT / path).read_text())


def verify_snapshots():
    # Stop if a copied source has changed since it was recorded.
    for item in read_json("manifest.json"):
        actual = hashlib.sha256((ROOT / item["snapshot"]).read_bytes()).hexdigest()
        if actual != item["sha256"]:
            raise ValueError("Changed evidence: " + item["snapshot"])


def cell(value, digits=2):
    return f"{value:.{digits}f}"


def ratio(stats):
    return f"{stats['median']:.2f} [{stats['min']:.2f}, {stats['max']:.2f}]"


def scientific(value):
    mantissa, exponent = f"{value:.1e}".split("e")
    return rf"${mantissa}\times10^{{{int(exponent)}}}$"


def table(name, columns, header, rows, caption):
    # Captions state the denominator and the direction of each ratio.
    body = [
        "% Generated by analysis/generate_tables.py. Do not edit by hand.",
        r"\begin{table}[tbp]", r"\centering\normalsize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{" + caption + "}",
        r"\label{tab:" + name + "}",
        r"\begin{tabular}{" + columns + "}", r"\toprule",
        " & ".join(header) + r" \\", r"\midrule",
    ]
    body.extend(" & ".join(map(str, row)) + r" \\" for row in rows)
    body.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    return "\n".join(body)


def generate():
    verify_snapshots()
    saved = read_json("summary_v3.json")
    frozen = read_json("summary.json")
    assert frozen["totals"]["hypotheses"] == 113644
    assert sum(v["hypotheses"] for v in frozen["audits"].values()) == 113644
    assert saved["audit_v2_K3"]["all"]["counts"]["HGB hypotheses"] == 36 * 696
    assert saved["audit_confirmation_K3"]["all"]["counts"]["HGB hypotheses"] == 140995
    output = {}

    rows = []
    for label, key in [("W1, $K=3$", "v2_K3"), ("W1, $K=5$", "v2_K5"),
                       ("W2, $K=3$", "confirmation_K3")]:
        v = saved["verification"][key]
        rows.append([label, v["cases"], v["probes"],
                     scientific(v["max_abs_error_compiled_vs_replay"]),
                     scientific(v["max_normwise_relative_error"])])
    output["verification"] = table(
        "verification", "lrrrr", ["Workload", "Cases", "Probes", "Max. absolute error", "Max. relative error"], rows,
        "Independent replay checks on real histories. Errors compare compiled walk states with physical deletion and replay. "
        "The relative error is normalised by the largest absolute reference entry. These are maxima over the recorded probes, not error bounds.")

    rows = []
    for dataset, label in [("mooc", "MOOC"), ("wikipedia", "Wikipedia"), ("lastfm", "LastFM")]:
        for policy, pool in [("source", "Recent-source"), ("uniform", "Dispersed")]:
            v = frozen["audits"][dataset + "_" + policy]
            assert v["flip1"] + v["flip2"] + v["no_flip"] == v["n_queries"] == 12
            rows.append([label, pool, cell(v["compiled_median_seconds"], 3),
                         cell(v["control_median_seconds"], 3),
                         f"{v['ratio_median']:.2f} [{v['ratio_min']:.2f}, {v['ratio_max']:.2f}]",
                         f"{v['flip1']}/{v['flip2']}/{v['no_flip']}"])
    output["frozen"] = table(
        "frozen", "llrrrc", ["Dataset", "Pool", "ETWC (s)", "Control (s)", "Control/ETWC", "1/2/none"], rows,
        "Frozen audits at $K=3$; 12 queries per row. Times are medians. "
        "Ratios are case-wise medians [observed range]; above one favours ETWC. "
        "The control is the faster exact correction method per case. "
        "The last column counts minimum flip budgets of one, two, or no flip within the tested scope.")

    rows = []
    for label, suite, group in [("W1, all", "v2", None), ("W2, all", "confirmation", None),
                                ("W2, recent-source", "confirmation", "source"),
                                ("W2, dispersed", "confirmation", "uniform")]:
        b = saved[f"bench_{suite}_K3"]
        a = saved[f"audit_{suite}_K3"]
        br = (b["all"] if group is None else b["by_group"][group])["ratios"]
        ar = (a["all"] if group is None else a["by_policy"][group])["ratios"]
        state = br["source_lazy/eager total"]
        audit = ar["source_lazy/eager audit total HGB"]
        assert state["cases"] == audit["cases"]
        rows.append([label, state["cases"], ratio(state), ratio(audit)])
    output["matched"] = table(
        "matched", "lrrr", ["Workload", "Cases", r"\shortstack{State cost\\SB-Lazy/ETWC}", r"\shortstack{HGB audit cost\\SB-Lazy/ETWC}"], rows,
        "Matched exploratory costs at $K=3$. Entries are case-wise median ratios [observed range]; above one favours ETWC. "
        "State cost includes construction and cold evaluation. HGB audit cost adds features and scoring, excluding common recency-index setup. "
        "W2 policy rows are subsets of W2 all.")

    rows = []
    for label, suite in [("W1", "v2"), ("W2", "confirmation")]:
        r = saved[f"bench_{suite}_K3"]["all"]["ratios"]
        rows.append([label, cell(r["sparse/packed coefficients"]["median"], 3),
                     cell(r["sparse coefficient+index bytes / eager transfer bytes"]["median"], 3),
                     cell(r["sparse (all retained) / eager (all retained) bytes"]["median"], 3),
                     cell(r["sparse_compact/eager total"]["median"]),
                     cell(r["sparse/packed total"]["median"])])
    output["storage"] = table(
        "storage", "lrrrrr", ["Workload", "Coefficients", "Transfer bytes", "All bytes", "State/dense", "State/packed"], rows,
        "Median Sparse-ETWC ratios at $K=3$; smaller is better. Coefficients are relative to packed transfers. "
        "Transfer bytes include indices and are relative to dense transfers. All bytes cover retained arrays relative to dense ETWC, not peak memory. "
        "State costs are relative to dense or packed ETWC. W1 has 36 cases; W2 has 72. "
        "W2 coefficients use 71 defined ratios because one denominator is zero.")

    rows = []
    for depth in [2, 3, 4, 5]:
        r = saved[f"bench_v2_K{depth}"]["all"]["ratios"]
        c = saved[f"audit_v2_K{depth}"]["all"]["counts"]
        assert c["HGB hypotheses"] == 25056
        rows.append([depth, f"{100*r['certified fraction']['median']:.0f}\\%",
                     cell(r["sparse/packed coefficients"]["median"], 3),
                     f"{c['HGB ie score diff > 1e-8']:,}", c["HGB ie top1 disagreements"],
                     c["HGB cases minimum budget disagrees"]])
    output["depth"] = table(
        "depth", "rrrrrr", ["Depth", "Certified", "Coefficients", "Score differences", "Top-1", "Budget"], rows,
        "W1 depth sweep: 36 cases and 25,056 hypotheses per depth, with a separately fitted fixed HGB model. "
        "Certified and coefficients are median certificate coverage and sparse/packed coefficient ratio. "
        "Score differences count IE versus exact errors above $10^{-8}$; top-1 counts different best destinations. "
        "Budget counts cases with a different minimum flip budget.")

    rows = []
    for method, key in [("Pair-Lazy", "pair_lazy"), ("Packed ETWC", "packed_compact"),
                         ("Per-source sparse", "sparse_per_source"),
                         ("Independent Effects", "independent_effects"), ("Adaptive", "adaptive")]:
        rows.append([method] + [ratio(saved[f"bench_{suite}_K3"]["all"]["ratios"][key + "/eager total"])
                               for suite in ["v2", "confirmation"]])
    output["additional"] = table(
        "additional", "lrr", ["Evaluator", "W1: evaluator/ETWC", "W2: evaluator/ETWC"], rows,
        "Additional exploratory state-cost comparisons at $K=3$, with 36 W1 cases and 72 W2 cases. "
        "Entries are median case-wise ratios and observed ranges. Ratios above one mean the named evaluator costs more than eager ETWC. "
        "Independent Effects is approximate outside the sufficient certificate. The other evaluators are exact.")

    # Keep headline quantities traceable to the same input summaries.
    output["metrics"] = "\n".join([
        "% Generated headline values. The source is the copied JSON evidence.",
        r"\newcommand{\FrozenHypotheses}{" + f"{frozen['totals']['hypotheses']:,}" + "}",
        r"\newcommand{\LargestReplayError}{" + scientific(max(v["max_normwise_relative_error"] for v in saved["verification"].values())) + "}",
        "",
    ])
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check existing tables without changing them.")
    args = parser.parse_args()
    output = generate()
    for name, content in output.items():
        path = TABLES / (name + ".tex")
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise ValueError("Table needs regeneration: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"{'Checked' if args.check else 'Generated'} {len(output)-1} tables and headline macros. Evidence hashes match.")


if __name__ == "__main__":
    main()
